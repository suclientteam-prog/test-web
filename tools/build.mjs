// Rebuilds js/assets.js from the files in assets/ and writes tools/lines.json
// (every voice line of js/lessons.js) for tools/make_audio.py.
// Usage: node tools/build.mjs        (prints the lines that still have no mp3)
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sandbox = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(root, "js/lessons.js"), "utf8"), sandbox);
const lines = sandbox.window.LESSONS.allLines();
fs.writeFileSync(path.join(root, "tools/lines.json"), JSON.stringify(lines, null, 1) + "\n");

const list = (dir, ext) => fs.readdirSync(path.join(root, dir)).filter(f => f.endsWith(ext)).sort().map(f => f.slice(0, -ext.length));
const audio = list("assets/audio", ".mp3");
const img = list("assets/images", ".webp");
const obj = (keys, dir, ext) => "{\n" + keys.map(k => `    ${JSON.stringify(k)}: "${dir}/${k}${ext}"`).join(",\n") + "\n  }";
fs.writeFileSync(path.join(root, "js/assets.js"),
  "// Media list – generated by tools/build.mjs, do not edit by hand.\n" +
  `window.ASSETS = {\n  audio: ${obj(audio, "assets/audio", ".mp3")},\n  img: ${obj(img, "assets/images", ".webp")}\n};\n`);

const missing = Object.keys(lines).filter(k => !audio.includes(k));
const unused = audio.filter(k => !lines[k] && k !== "bg_music");
const words = sandbox.window.LESSONS.WORDS.filter(w => !img.includes(w.id)).map(w => w.id);
console.log(`lines: ${Object.keys(lines).length}  audio: ${audio.length}  images: ${img.length}`);
if (missing.length) console.log(`no mp3 yet (${missing.length}): ${missing.join(" ")}`);
if (unused.length) console.log(`mp3 not used by any line (${unused.length}): ${unused.join(" ")}`);
if (words.length) console.log(`words without a picture: ${words.join(" ")}`);
